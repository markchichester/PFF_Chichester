  /** Interpolate LMS at fractional months */
  lmsAt(table, months) {
    const m = Math.max(0, Math.min(24, months));
    const lo = Math.floor(m);
    const hi = Math.min(24, Math.ceil(m));
    if (lo === hi) {
      const [L, M, S] = table[lo];
      return { L, M, S };
    }
    const t = m - lo;
    const a = table[lo];
    const b = table[hi];
    return {
      L: a[0] + (b[0] - a[0]) * t,
      M: a[1] + (b[1] - a[1]) * t,
      S: a[2] + (b[2] - a[2]) * t
    };
  },

  zScore(value, L, M, S) {
    if (!(value > 0) || !(M > 0) || !(S > 0)) return null;
    if (Math.abs(L) < 1e-7) return Math.log(value / M) / S;
    return (Math.pow(value / M, L) - 1) / (L * S);
  },

  /** Approximate Φ(z) → percentile 0–100 */
  percentileFromZ(z) {
    if (z == null || Number.isNaN(z)) return null;
    // Abramowitz & Stegun 26.2.17
    const sign = z < 0 ? -1 : 1;
    const x = Math.abs(z) / Math.SQRT2;
    const t = 1 / (1 + 0.3275911 * x);
    const a1 = 0.254829592, a2 = -0.284496736, a3 = 1.421413741, a4 = -1.453152027, a5 = 1.061405429;
    const erf = 1 - (((((a5 * t + a4) * t) + a3) * t + a2) * t + a1) * t * Math.exp(-x * x);
    const p = 0.5 * (1 + sign * erf);
    return Math.max(0.1, Math.min(99.9, p * 100));
  },

  formatPercentile(p) {
    if (p == null) return "—";
    if (p < 1) return "<1st";
    if (p > 99) return ">99th";
    const n = Math.round(p);
    const mod10 = n % 10;
    const mod100 = n % 100;
    let suf = "th";
    if (mod10 === 1 && mod100 !== 11) suf = "st";
    else if (mod10 === 2 && mod100 !== 12) suf = "nd";
    else if (mod10 === 3 && mod100 !== 13) suf = "rd";
    return n + suf;
  },

  /**
   * @param {sex:'male'|'female', ageMonths:number, weightKg?:number, lengthCm?:number}
   */
  calc({ sex, ageMonths, weightKg, lengthCm }) {
    const s = sex === "female" ? "female" : "male";
    const out = { weightPct: null, lengthPct: null, weightZ: null, lengthZ: null };
    if (ageMonths == null || ageMonths < 0) return out;
    if (weightKg != null) {
      const { L, M, S } = this.lmsAt(this.weight[s], ageMonths);
      out.weightZ = this.zScore(weightKg, L, M, S);
      out.weightPct = this.percentileFromZ(out.weightZ);
    }
    if (lengthCm != null) {
      const { L, M, S } = this.lmsAt(this.length[s], ageMonths);
      out.lengthZ = this.zScore(lengthCm, L, M, S);
      out.lengthPct = this.percentileFromZ(out.lengthZ);
    }
    return out;
  }
